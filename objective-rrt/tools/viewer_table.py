#!/usr/bin/env python3
"""Put every run's first-success replays in sm64-viewer, as one timeline entry
with a table: a row per run, a column per objective type, and in each cell the
game time (from power-on) of that run's first success of that type, which plays
the replay when clicked.

    tools/viewer_table.py [runs_dir] [viewer_replays_dir]

Copies runs/<run>/{first,frontier}-*.m64 to <viewer>/obrrt/<run>/ and replaces
the "Objective-based RRT: first success per run" entry of index.json. Rerun it
after each run.
"""

import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "runs"
VIEWER = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parents[2] / "sm64-viewer/frontend/public/replays"
TITLE = "Objective-based RRT: first success per run"

# Rough order of how far into the game each type gets.
ORDER = [
    "Mario::PosDist", "Mario::PosTime", "Mario::Settle", "Mario::Wait", "Mario::GoToCastle", "Door::Enter",
    "Painting::Enter", "Coin::Collect", "Enemy::Defeat", "Object::Break", "Object::Grab",
    "Npc::Talk", "Boss::Hit", "Star::Collect",
]
# Raw inputs, 4 bytes a frame, as engine.rs writes them (no Mupen header).
FPS = 30
# How long before the end of a replay to start it, so the success is in view
# (the end includes the tail that waits for Mario to be controllable again).
LEAD = 450


def frames(path: Path) -> int:
    return path.stat().st_size // 4


def inputs(path: Path) -> bytes:
    return path.read_bytes()


def clock(f: int) -> str:
    s = f / FPS
    return f"{int(s // 60)}:{s % 60:04.1f}"


def run_key(name: str):
    m = re.match(r"([a-z]+)(\d+)$", name)
    return (0 if name.startswith("v") else 1, m[1] if m else name, int(m[2]) if m else 0)


def main():
    summit = RUNS / "summit.m64"
    summit_inputs = inputs(summit) if summit.exists() else None
    runs = sorted((d for d in RUNS.iterdir() if d.is_dir() and any(d.glob("first-*.m64"))), key=lambda d: run_key(d.name))

    found = {}  # run -> kind -> (file, frames)
    for d in runs:
        out = VIEWER / "obrrt" / d.name
        out.mkdir(parents=True, exist_ok=True)
        found[d.name] = {}
        for m64 in sorted(d.glob("first-*.m64")) + sorted(d.glob("frontier-*.m64")):
            shutil.copyfile(m64, out / m64.name)
            if m64.name.startswith("first-"):
                kind = m64.stem.removeprefix("first-").replace("-", "::", 1)
                found[d.name][kind] = (f"obrrt/{d.name}/{m64.name}", frames(m64))

    kinds = [k for k in ORDER if any(k in f for f in found.values())]
    kinds += sorted({k for f in found.values() for k in f} - set(kinds))

    rows = []
    for d in runs:
        summary = d / "summary.json"
        s = json.loads(summary.read_text()) if summary.exists() else None
        # A run that started from the summit has the summit's inputs as its prefix.
        any_m64 = next(iter(sorted(d.glob("first-*.m64"))))
        from_summit = summit_inputs is not None and inputs(any_m64).startswith(summit_inputs)
        cells = [
            d.name if s else f"{d.name} (running)",
            "summit (v5)" if from_summit else "power-on",
            round(s["secs"] / 60, 1) if s else "—",
            s["nodes"] if s else "—",
        ]
        for k in kinds:
            if k in found[d.name]:
                file, f = found[d.name][k]
                cells.append({"text": clock(f), "file": file, "start": max(0, f - LEAD),
                              "title": f"{d.name}: first {k} at frame {f:,} ({clock(f)} from power-on). Click to play."})
            else:
                cells.append("—")
        rows.append({"cells": cells})

    entry = {
        "date": "2026-10-23T12:00:00Z",
        "title": TITLE,
        "description": "Each search run of Objective-based RRT (sm64-AI-binds/objective-rrt). A cell is the game time, "
                       "from power-on, of the run's first success of that objective type; click it to watch that replay "
                       "(it starts 15 s before the end). king1 and king2 continued from v5's summit state.",
        "important": True,
        "table": {
            "columns": ["Run", "Start", "Search (min)", "States"] + [k.replace("::", "::\u200b") for k in kinds],
            "rows": rows,
            "note": "— means the run never completed that objective type. Times are game time at 30 frames per second, "
                    "including the 1,690 frames of menus and intro. Generated by objective-rrt/tools/viewer_table.py.",
        },
    }

    index_path = VIEWER / "index.json"
    index = json.loads(index_path.read_text())
    index = [e for e in index if e.get("title") != TITLE] + [entry]
    index_path.write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n")
    print(f"{len(rows)} runs × {len(kinds)} objective types -> {index_path}")


if __name__ == "__main__":
    main()
