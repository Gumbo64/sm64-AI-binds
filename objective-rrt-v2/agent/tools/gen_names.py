#!/usr/bin/env python3
"""Generates agent/src/inspect/names.rs (name tables for `ar`) from the decomp headers.

Run from anywhere: python3 agent/tools/gen_names.py
"""
import re, pathlib, sys

PORT = pathlib.Path("/workspaces/sm64-combined/sm64-binds/sm64-port")
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/inspect/names.rs"


def read(p):
    return (PORT / p).read_text(errors="replace")


def defines(text, prefix, skip=()):
    """[(name, value)] of `#define PREFIX... value` (hex, decimal, `(1 << n)` or `(a | b)`)."""
    out = []
    for m in re.finditer(r"^#define\s+(%s\w*)\s+(.*)$" % prefix, text, re.M):
        name, rest = m.group(1), m.group(2)
        if name in skip:
            continue
        rest = re.sub(r"/\*.*?\*/", "", rest)
        rest = rest.split("//")[0].strip()
        if not rest or not re.fullmatch(r"[0-9a-fA-FxX()<| ]+", rest):
            continue
        try:
            v = eval(rest, {"__builtins__": {}})
        except Exception:
            continue
        out.append((name, int(v)))
    return out


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table(name, ty, items, width=None):
    lines = [f"pub static {name}: &[({ty}, &str)] = &["]
    for v, n in items:
        lines.append(f"    ({v}, {rs_str(n)}),")
    lines.append("];\n")
    return "\n".join(lines)


def uniq_sorted(pairs, mask=None):
    seen, out = set(), []
    for n, v in sorted(pairs, key=lambda p: p[1]):
        if v in seen:
            continue
        seen.add(v)
        out.append((v, n))
    return out


def main():
    sm64 = read("include/sm64.h")
    acts = [(n, v) for n, v in defines(sm64, "ACT_") if v > 0x1FF and not n.startswith("ACT_FLAG") and not n.startswith("ACT_GROUP") and n != "ACT_ID_MASK"]
    surf = defines(read("include/surface_terrains.h"), "SURFACE_")
    save = defines(read("src/game/save_file.h"), "SAVE_FLAG_", skip=("SAVE_FLAG_TO_STAR_FLAG", "STAR_FLAG_TO_SAVE_FLAG"))
    mflags = defines(sm64, "MARIO_", skip=())
    mflags = [(n, v) for n, v in mflags if 0 < v < 1 << 32 and bin(v).count("1") == 1 and not n.startswith(("MARIO_ANIM", "MARIO_UNKNOWN_1", "MARIO_UNKNOWN_0"))]
    mflags = [(n, v) for n, v in mflags if re.match(r"MARIO_(NORMAL|VANISH|METAL|WING|CAP|TELEPORT|ACTION|MARIO|PUNCH|KICK|TRIP|UNKNOWN)", n)]
    actflags = [(n, v) for n, v in defines(sm64, "ACT_FLAG_")]
    inter = defines(read("src/game/interaction.h"), "INTERACT_")
    status = [(n, v) for n, v in defines(read("src/game/interaction.h"), "INT_STATUS_") if bin(v).count("1") == 1]
    oconst = read("include/object_constants.h")
    oflags = defines(oconst, "OBJ_FLAG_")
    active = [(n, v) for n, v in defines(oconst, "ACTIVE_FLAG_") if v]

    # courses: enum order, comment gives the name
    course_txt = read("levels/course_defines.h")
    courses = []
    for m in re.finditer(r"DEFINE_(?:BONUS_)?COURSE\((\w+),\s*0x[0-9a-fA-F]+\)\s*//\s*\((\d+)\)\s*(.*)", course_txt):
        courses.append((int(m.group(2)), m.group(1), m.group(3).strip()))
    courses.sort()
    cname = {c[1]: c[2] for c in courses}

    # levels: enum order from level_defines.h (LEVEL_NONE = 0)
    ld = read("levels/level_defines.h")
    levels = []
    idx = 1
    over = {
        "LEVEL_CASTLE": "Castle (inside)", "LEVEL_CASTLE_GROUNDS": "Castle Grounds", "LEVEL_CASTLE_COURTYARD": "Castle Courtyard",
        "LEVEL_BOWSER_1": "Bowser in the Dark World (boss)", "LEVEL_BOWSER_2": "Bowser in the Fire Sea (boss)",
        "LEVEL_BOWSER_3": "Bowser in the Sky (boss)", "LEVEL_ENDING": "Ending",
    }
    for m in re.finditer(r"^(STUB_LEVEL|DEFINE_LEVEL)\(\s*\"[^\"]*\",\s*(\w+),\s*(\w+)", ld, re.M):
        enum, course = m.group(2), m.group(3)
        if m.group(1) == "STUB_LEVEL":
            nm = "(unused)"
        else:
            nm = over.get(enum) or cname.get(course, enum)
        levels.append((idx, enum, nm))
        idx += 1

    out = ["// generated by tools/gen_names.py, do not edit", "#![allow(dead_code)]", ""]
    out.append("/// (ACT_* value including group/flags, name), sorted by value.")
    out.append(table("ACTIONS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(acts)]))
    out.append("/// (SURFACE_* type, name), sorted by value.")
    out.append(table("SURFACES", "i16", [(f"{v:#06x}", n) for v, n in uniq_sorted(surf)]))
    out.append("/// (flag bit, SAVE_FLAG_* name), sorted by value.")
    out.append(table("SAVE_FLAGS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(save)]))
    out.append("/// (flag bit, MARIO_* name) for `MarioState.flags`.")
    out.append(table("MARIO_FLAGS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(mflags)]))
    out.append("/// (flag bit, ACT_FLAG_* name) for the high bits of `MarioState.action`.")
    out.append(table("ACT_FLAGS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(actflags)]))
    out.append("/// (interact type bit, INTERACT_* name).")
    out.append(table("INTERACTS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(inter)]))
    out.append("/// (oInteractStatus bit, INT_STATUS_* name).")
    out.append(table("INT_STATUS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(status)]))
    out.append("/// (oFlags bit, OBJ_FLAG_* name).")
    out.append(table("OBJ_FLAGS", "u32", [(f"{v:#010x}", n) for v, n in uniq_sorted(oflags)]))
    out.append("/// (activeFlags bit, ACTIVE_FLAG_* name).")
    out.append(table("ACTIVE_FLAGS", "u32", [(f"{v:#06x}", n) for v, n in uniq_sorted(active)]))
    out.append("/// (level number, LEVEL_* enum, readable name), sorted by number.")
    out.append("pub static LEVELS: &[(u16, &str, &str)] = &[")
    for i, e, n in levels:
        out.append(f"    ({i}, {rs_str(e)}, {rs_str(n)}),")
    out.append("];\n")
    out.append("/// (course number, COURSE_* enum, readable name), sorted by number.")
    out.append("pub static COURSES: &[(i16, &str, &str)] = &[")
    for i, e, n in courses:
        out.append(f"    ({i}, {rs_str(e)}, {rs_str(n)}),")
    out.append("];\n")
    out.append(r'''fn find<T: Copy + Ord, N: Copy>(t: &'static [(T, N)], k: T) -> Option<N> {
    t.binary_search_by_key(&k, |e| e.0).ok().map(|i| t[i].1)
}

pub fn action_name(a: u32) -> &'static str {
    find(ACTIONS, a).unwrap_or("ACT_?")
}

pub fn surface_name(t: i16) -> &'static str {
    find(SURFACES, t).unwrap_or("SURFACE_?")
}

pub fn level_name(l: u16) -> &'static str {
    LEVELS.binary_search_by_key(&l, |e| e.0).ok().map_or(if l == 0 { "(none)" } else { "?" }, |i| LEVELS[i].2)
}

pub fn level_enum(l: u16) -> &'static str {
    LEVELS.binary_search_by_key(&l, |e| e.0).ok().map_or("?", |i| LEVELS[i].1)
}

pub fn course_name(c: i16) -> &'static str {
    COURSES.binary_search_by_key(&c, |e| e.0).ok().map_or(if c == 0 { "Castle / hub" } else { "?" }, |i| COURSES[i].2)
}

/// Names of the set bits of `v` in `table` (plus `0x..` for unnamed bits).
pub fn bits(table: &'static [(u32, &'static str)], v: u32) -> Vec<String> {
    let mut out: Vec<String> = table.iter().filter(|(b, _)| v & b == *b && *b != 0).map(|(_, n)| n.to_string()).collect();
    let known = table.iter().fold(0, |a, (b, _)| a | b);
    if v & !known != 0 {
        out.push(format!("{:#x}", v & !known));
    }
    out
}
''')
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(acts)} actions, {len(surf)} surfaces, {len(save)} save flags, {len(levels)} levels, {len(courses)} courses")


main()
