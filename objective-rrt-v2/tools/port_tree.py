#!/usr/bin/env python3
"""Ports the tree viewer page (viz/index.html) into the sm64-viewer app:
src/tree/treeview.js (a mountTree(root, opts) module) and src/tree/tree.css
(styles scoped under .tree-app). viz/index.html stays the source: edit it and
rerun this script.
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "viz", "index.html")
OUT = os.path.normpath(os.path.join(HERE, "../../../sm64-viewer/frontend/src/tree"))


def scope(css):
    """Prefixes every rule's selectors with .tree-app (:root, html, body and
    .app become .tree-app itself)."""
    out, depth, start, blocks = [], 0, 0, []
    for j, ch in enumerate(css):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                blocks.append(css[start : j + 1])
                start = j + 1
    for blk in blocks:
        blk = blk.strip()
        sel, rest = blk.split("{", 1)
        sel = sel.strip()
        if sel.startswith("@keyframes"):
            out.append(blk)
            continue
        if sel.startswith("@media"):
            out.append(sel + " {\n" + scope(rest.rsplit("}", 1)[0]) + "\n}")
            continue
        sels = []
        for s in sel.split(","):
            s = s.strip()
            if s in (":root", "html", "body", ".app"):
                sels.append(".tree-app")
            elif s == "*":
                sels.append(".tree-app *")
            elif s.startswith(".app "):
                sels.append(".tree-app " + s[5:])
            else:
                sels.append(".tree-app " + s)
        out.append(", ".join(dict.fromkeys(sels)) + " {" + rest)
    return "\n".join(out)


def must(js, old, new):
    assert old in js, f"not found: {old[:80]!r}"
    return js.replace(old, new)


def main():
    src = open(SRC).read()
    css = src[src.index("<style>") + 7 : src.index("</style>")]
    body = src[src.index('<div class="app">') : src.index('<script type="module">')].strip()
    js = src[src.index('<script type="module">') + len('<script type="module">') : src.index("</script>\n</body>")]

    css = "/* Scoped copy of objective-rrt/viz/index.html's styles, generated by tools/port_tree.py. */\n" + scope(css)
    # Full-window page over the app.
    css = css.replace(".tree-app {", ".tree-app {\n  position: fixed; inset: 0; z-index: 1;", 1)

    body = body.replace('<div class="app">', "", 1)
    body = body[: body.rstrip().rfind("</div>")].strip()
    body = must(body, "<h1>Objective-RRT tree</h1>",
                '<button id="back" title="Back to the replay list">← Replays</button>\n    <h1>Objective-RRT tree</h1>')

    js = must(js, "import * as THREE from 'three';\nimport { OrbitControls } from 'three/addons/controls/OrbitControls.js';\n", "")
    js = js.replace("document.getElementById(", "$(").replace("document.querySelectorAll(", "root.querySelectorAll(")
    js = must(js, "document.addEventListener('click', (e) => {", "root.addEventListener('click', (e) => {")
    js = must(js, "let playHook = null;", "let playHook = opts.onPlay ?? null;")
    js = must(js, "new ResizeObserver(resize).observe(view);", "const resizeObs = new ResizeObserver(resize);\nresizeObs.observe(view);")
    js = must(js, "(function loop() { controls.update();", "(function loop() { if (disposed) return; controls.update();")
    js = must(js, "async function showNode(id, focus = true) {\n  selected = id;", "async function showNode(id, focus = true) {\n  selected = id;\n  report();")
    tail_start = js.index("data = liveSource('');")
    js = js[:tail_start] + """$('back').addEventListener('click', () => opts.onBack?.());

(async () => {
  // The live server if it answers (and isn't turned off), else the static
  // exports (GitHub Pages).
  data = null;
  if (!opts.staticOnly) {
    const live = liveSource(api);
    try { if ((await live.runs()).length) data = live; } catch { /* no server */ }
  }
  if (!data) data = staticSource(opts.staticBase);
  // The app reads level geometry from the user's own ROM (never shipped).
  if (opts.geometry) data.geometry = opts.geometry;
  try {
    levelNames = await data.levels();
    await loadRuns();
  } catch {
    $('zones').innerHTML = `<div class="empty">No trees found: neither the tree server (${esc(api)}, start it with <code>python3 tools/viz.py</code> in objective-rrt) nor static exports (${esc(opts.staticBase)}, made by <code>tools/export_tree.py</code>).</div>`;
    return;
  }
  if (opts.run && [...$('run').options].some((o) => o.value === opts.run)) $('run').value = opts.run;
  run = $('run').value;
  if (opts.zone) zoneKey = opts.zone;
  await refresh(true);
  if (opts.node != null && byId[opts.node]) showNode(opts.node);
  report();
  if (!disposed && data.live) timer = setInterval(tick, 5000);
})();

return () => {
  disposed = true;
  clearInterval(timer);
  resizeObs.disconnect();
  controls.dispose();
  renderer.dispose?.();
  root.innerHTML = '';
  root.classList.remove('tree-app');
};"""

    module = f"""// The Objective-RRT tree view, mounted into a container by TreeView.jsx.
// Generated from objective-rrt/viz/index.html by objective-rrt/tools/port_tree.py:
// edit that page and rerun the script instead of editing this file.
//
// opts: {{ api, staticBase, staticOnly?, geometry?(level, area), run?, zone?, node?, onPlay({{ url, start, title, state }}), onBack(), onState({{ run, zone, node }}) }}
/* eslint-disable */
import * as THREE from 'three';
import {{ OrbitControls }} from 'three/examples/jsm/controls/OrbitControls.js';
import './tree.css';

const TEMPLATE = {json.dumps(body)};

export function mountTree(root, opts) {{
root.classList.add('tree-app');
root.innerHTML = TEMPLATE;
const api = opts.api;
const $ = (id) => root.querySelector('#' + id);
let disposed = false, timer = null;
// Tells the app the run, area and selection, so the page URL can restore them.
const report = () => opts.onState?.({{ run, zone: zoneKey, node: selected }});
{js}
}}
"""
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "treeview.js"), "w").write(module)
    open(os.path.join(OUT, "tree.css"), "w").write(css)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
